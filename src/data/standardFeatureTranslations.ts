const fallbackTranslate = (text: string, lang: Lang) => {
  if (lang === 'zh') return translateValueToZh(text);
  if (lang === 'es') return translateValueToEs(text);
  if (lang === 'fr') return translateValueToFr(text);
  if (lang === 'vi') return translateValueToVi(text);
  if (lang === 'km') return translateValueToKm(text);
  if (lang === 'ar') return translateValueToAr(text);
  return text;
};

export const translateStandardFeature = (text: string, lang: Lang) => {
  if (lang === 'en') return text;
  return featureTranslations[text]?.[lang] || fallbackTranslate(text, lang);
};
