import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
const require = createRequire(process.env.PLAYWRIGHT_PACKAGE || import.meta.url);
const { chromium } = require('playwright');
const browser = await chromium.launch({headless:true, channel:'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors = [];
page.on('pageerror', e=>errors.push(e.message));
page.on('dialog', d=>d.accept());
try {
  await page.goto(process.env.QUOTER_URL || 'http://localhost:3000');
  await page.getByLabel('Description preset', {exact:true}).selectOption('Platform Lift');
  const functions = page.getByRole('heading', {name:'Platform Lift Functions', exact:true});
  await functions.waitFor();
  assert.equal(await page.getByRole('heading', {name:/Standard Features/}).count(), 0);
  const functionTable = functions.locator('..').locator('tbody tr');
  assert.equal(await functionTable.count(), 29);
  assert.equal(await page.locator('.print-only-full-width').getByRole('cell', {name:'Hpmont',exact:true}).count(), 5);
  await functions.scrollIntoViewIfNeeded();
  await page.screenshot({path:join(tmpdir(),'quoter-platform-desktop.png')});
  await page.getByRole('button',{name:'+ 添加电梯',exact:true}).click();
  await page.getByLabel('Description preset',{exact:true}).last().selectOption('Passenger Lift');
  await page.getByRole('heading',{name:'Standard Elevator',exact:true}).waitFor();
  await functions.waitFor();
  await page.getByRole('button',{name:'保存到报价库',exact:true}).click();
  await page.waitForTimeout(500);
  await page.reload();
  await functions.waitFor();
  await page.getByRole('heading',{name:'Standard Elevator',exact:true}).waitFor();
  await page.getByRole('button',{name:'其他导出格式',exact:true}).click();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button',{name:'导出 Word',exact:true}).click();
  const proceed = page.getByRole('button',{name:'仍然导出',exact:true});
  if (await proceed.count()) await proceed.click();
  const download = await downloaded;
  await download.saveAs(join(tmpdir(),'quoter-platform-mixed.docx'));
  await page.emulateMedia({media:'print'});
  await page.pdf({path:join(tmpdir(),'quoter-platform-mixed.pdf'),format:'A4',printBackground:true});
  await page.emulateMedia({media:'screen'});
  await page.setViewportSize({width:390,height:844});
  await functions.scrollIntoViewIfNeeded();
  await page.screenshot({path:join(tmpdir(),'quoter-platform-mobile.png')});
  assert.deepEqual(errors, []);
  console.log('PASS platform defaults, mixed appendices, save/reload, Word and PDF export, desktop/mobile render');
} finally { await browser.close(); }
